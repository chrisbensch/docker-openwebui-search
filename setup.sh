#!/usr/bin/env bash
set -Eeuo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${ROOT_DIR}/.env"

cd "${ROOT_DIR}"

log() {
  printf '[setup] %s\n' "$*"
}

die() {
  printf '[setup] ERROR: %s\n' "$*" >&2
  exit 1
}

require_command() {
  command -v "$1" >/dev/null 2>&1 || die "Required command not found: $1"
}

ensure_env_var() {
  local key="$1"
  local value="$2"

  if ! grep -q "^${key}=" "${ENV_FILE}"; then
    printf '%s=%s\n' "${key}" "${value}" >> "${ENV_FILE}"
  fi
}

ensure_secret() {
  local key="$1"

  if ! grep -q "^${key}=" "${ENV_FILE}"; then
    ensure_env_var "${key}" "$(openssl rand -hex 32)"
  fi
}

wait_for_search_from_open_webui() {
  local attempt

  for attempt in $(seq 1 12); do
    if docker compose exec -T open-webui python - >/dev/null 2>&1 <<'PY'
import json
from urllib.request import Request, urlopen

request = Request(
    "http://firecrawl-api:3002/v2/search",
    data=json.dumps({"query": "Python documentation", "limit": 3, "timeout": 9000}).encode(),
    headers={"Content-Type": "application/json"},
)
with urlopen(request, timeout=15) as response:
    results = json.load(response)["data"]["web"]
if not results:
    raise SystemExit("Firecrawl returned no web results")
PY
    then
      log 'Firecrawl search is ready from Open WebUI.'
      return 0
    fi
    sleep 5
  done

  return 1
}

show_diagnostics() {
  printf '\n[setup] Stack diagnostics:\n' >&2
  docker compose ps >&2 || true
  printf '\n[setup] Recent search service logs:\n' >&2
  docker compose logs --tail=40 firecrawl-api searxng searxng-core >&2 || true
  printf '\n[setup] Recent Open WebUI logs:\n' >&2
  docker compose logs --tail=80 open-webui >&2 || true
}

require_command docker
require_command openssl

docker compose version >/dev/null 2>&1 \
  || die 'Docker Compose v2 is required.'
docker info >/dev/null 2>&1 \
  || die 'The Docker daemon is unavailable or this user lacks permission.'

if [[ ! -e "${ENV_FILE}" ]]; then
  umask 077
  printf '# Generated by setup.sh; keep this file private.\n' > "${ENV_FILE}"
fi
chmod 0600 "${ENV_FILE}"

ensure_env_var COMPOSE_PROJECT_NAME open-webui-search
ensure_secret WEBUI_SECRET_KEY
ensure_secret SEARXNG_SECRET
ensure_secret FIRECRAWL_POSTGRES_PASSWORD
ensure_secret FIRECRAWL_BULL_AUTH_KEY

mkdir -p data/open-webui
docker compose config --quiet
log 'Building and starting Open WebUI and the search services.'
docker compose up -d --build --wait --wait-timeout 180

if ! wait_for_search_from_open_webui; then
  show_diagnostics
  die 'Open WebUI could not retrieve search results through Firecrawl and SearXNG.'
fi
